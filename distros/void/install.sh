#!/bin/sh
set -e
P=distros/void
L=/usr/local/libexec/schema-init
SHIMS="halt reboot poweroff shutdown"
[ "$(id -u)" = 0 ] || { echo "run as root" >&2; exit 1; }
[ -f $P/install.sh ] || { echo "run from the top of the schema-init tree" >&2; exit 1; }

if [ "${1:-}" = --remove ]; then
    rm -f /etc/grub.d/11_schema-init /usr/local/bin/sv
    for f in $SHIMS; do rm -f /usr/local/bin/$f; done
    rm -rf $L
    rm -f /usr/local/share/dbus-1/system-services/org.freedesktop.PolicyKit1.service
    grep -lx "# generated by schema-import --bus-overrides" /usr/local/share/dbus-1/system-services/*.service 2>/dev/null | xargs -r rm -f
    grub-mkconfig -o /boot/grub/grub.cfg
    echo "schema-init boot entries removed. /etc/schema-init and the binaries in /usr/bin are left in place."
    exit 0
fi

make install
install -d -m 0755 /etc/schema-init/services $L/shipped
install -m 0755 scripts/schema-mount-fstab $P/scripts/void-boot $P/scripts/void-coldplug $P/scripts/void-halt $L/
for f in $P/services/*.svc; do
    n=$(basename "$f"); t=/etc/schema-init/services/$n
    if [ -e "$t" ] && ! cmp -s "$t" "$f" && ! cmp -s "$t" "$L/shipped/$n"; then
        echo "kept your edited $t (new version: $f)"
    else
        install -m 0644 "$f" "$t"
        install -m 0644 "$f" "$L/shipped/$n"
    fi
done

install -m 0755 distros/fedora-installer/migrate/schema-import.py $L/schema-import
install -m 0644 $P/void-covered $L/void-covered
$L/schema-import --runit --after void-boot --rc-skip $L/void-covered || echo "schema-import failed: the services above still boot; the rest of /var/service does not run under schema-init."

install -m 0755 $P/scripts/sv /usr/local/bin/sv
for f in $SHIMS; do ln -sf $L/void-halt /usr/local/bin/$f; done

install -m 0755 distros/devuan/grub.d/11_schema-init /etc/grub.d/11_schema-init
grub-mkconfig -o /boot/grub/grub.cfg
if [ "$(cat /proc/1/comm)" = schema-init ]; then
    schema-ctl reexec || echo "PID 1 keeps running the previous schema-init until the next reboot."
fi
echo
echo "Installed. runit is still the default boot entry."
echo "Reboot and pick a 'schema-init:' entry in the GRUB menu to try it."
echo "After enabling a runit service (ln -s /etc/sv/X /var/service/), run:"
echo "  $L/schema-import --runit --after void-boot --rc-skip $L/void-covered --start"
