#!/usr/bin/env python3
# psf2c.py IN.psfu OUT.c — embed a 10x20, 256-glyph PSF2 in PID 1 (schema_font.c).
import struct
import sys


def main():
    raw = open(sys.argv[1], 'rb').read()
    magic, _, hsz, flags, n, bpg, h, w = struct.unpack_from('<8I', raw, 0)
    if magic != 0x864AB572 or (n, h, w) != (256, 20, 10) or not flags & 1:
        sys.exit('psf2c: want a 10x20 256-glyph PSF2 with a Unicode table')
    # KDFONTOP reads glyphs at a 32-row pitch: pad each 20-row glyph out to 32
    pad = b'\0' * (64 - bpg)
    glyph = b''.join(raw[hsz + i * bpg:hsz + (i + 1) * bpg] + pad for i in range(n))
    pairs, p = [], hsz + n * bpg
    for i in range(n):
        end = raw.index(b'\xff', p)
        for ch in raw[p:end].split(b'\xfe')[0].decode('utf-8'):
            pairs.append((ord(ch), i))
        p = end + 1
    pairs.sort()
    o = ['/* generated by tools/psf2c.py from fonts/schema-10x20.psfu: do not edit */',
         '#include <stddef.h>', '#include "rail_glyphs.h"', '',
         'const unsigned char schema_font_glyphs[256 * 64] = {']
    for i in range(0, len(glyph), 16):
        o.append('    ' + ', '.join(f'0x{b:02x}' for b in glyph[i:i + 16]) + ',')
    o.append('};')
    o.append('const struct unipair schema_font_unimap[] = {')
    for cp, pos in pairs:
        o.append(f'    {{ 0x{cp:04x}, {pos} }},')
    o.append('};')
    o.append(f'const unsigned schema_font_unimap_len = {len(pairs)};')
    o.append('''
int schema_font_has(uint32_t cp) {
    size_t lo = 0, hi = schema_font_unimap_len;
    while (lo < hi) {
        size_t mid = (lo + hi) / 2;
        if (schema_font_unimap[mid].unicode == cp) return 1;
        if (schema_font_unimap[mid].unicode < cp) lo = mid + 1;
        else hi = mid;
    }
    return 0;
}''')
    open(sys.argv[2], 'w').write('\n'.join(o) + '\n')


if __name__ == '__main__':
    main()
