#!/usr/bin/env python3
# Regenerate seccomp_names.h and seccomp_groups.h from systemd's syscall
# groups (`systemd-analyze syscall-filter`). Run by hand when systemd grows a
# syscall; the outputs are committed. Names become numbers at compile time
# (`#ifdef __NR_x`), so every architecture's build gets its own and drops the
# names it doesn't have.
import re
import subprocess
import sys

out = subprocess.run(["systemd-analyze", "syscall-filter"], capture_output=True, text=True, check=True).stdout
ver = subprocess.run(["systemd-analyze", "--version"], capture_output=True, text=True).stdout.split("\n")[0]
groups, cur = {}, None
for line in out.splitlines():
    if line.startswith("@"):
        cur = line.strip()
        groups[cur] = []
    elif cur and line.strip() and not line.strip().startswith("#"):
        groups[cur].append(line.strip())


def expand(g, seen=()):
    names = set()
    for m in groups[g]:
        if m.startswith("@"):
            if m not in seen:
                names |= expand(m, seen + (g,))
        else:
            names.add(m)
    return names


known = sorted(set(expand("@known")) | {n for g in groups for n in expand(g)})
for n in known:
    if not re.fullmatch(r"[a-z0-9_]+", n):
        sys.exit("odd syscall name: %r" % n)
idx = {n: i for i, n in enumerate(known)}
head = "/* generated by tools/gen-seccomp-tables.py from %s — do not edit */\n" % ver

with open("seccomp_names.h", "w") as f:
    f.write(head + "#ifndef SCHEMA_SECCOMP_NAMES_H\n#define SCHEMA_SECCOMP_NAMES_H\n\n#include <sys/syscall.h>\n\n")
    f.write("#define SC_NAMES_ALL %d\n\n" % len(known))
    f.write("/* every name systemd knows, on every arch: an unknown one refuses the load */\n")
    f.write("static const char *const sc_known[SC_NAMES_ALL] = {\n")
    for n in known:
        f.write('    "%s",\n' % n)
    f.write("};\n\n/* its number on this arch, -1 where this arch has no such syscall */\n")
    f.write("static const int sc_nr[SC_NAMES_ALL] = {\n")
    for n in known:
        f.write("#ifdef __NR_%s\n    __NR_%s,\n#else\n    -1,\n#endif\n" % (n, n))
    f.write("};\n\n#endif\n")

with open("seccomp_groups.h", "w") as f:
    f.write(head + "#ifndef SCHEMA_SECCOMP_GROUPS_H\n#define SCHEMA_SECCOMP_GROUPS_H\n\n")
    f.write("/* each group fully expanded to indexes into sc_known, 0xffff-terminated */\n")
    names = []
    for g in groups:
        c = "sc_g_" + g[1:].replace("-", "_")
        names.append((g, c))
        members = sorted(idx[n] for n in expand(g))
        f.write("static const unsigned short %s[] = { %s0xffff };\n" % (c, "".join("%d, " % i for i in members)))
    f.write("\nstatic const struct { const char *name; const unsigned short *idx; } sc_groups[] = {\n")
    for g, c in names:
        f.write('    { "%s", %s },\n' % (g, c))
    f.write("};\n#define SC_GROUPS (int)(sizeof sc_groups / sizeof sc_groups[0])\n\n#endif\n")
print("%d names, %d groups (%s)" % (len(known), len(groups), ver))
